// ── SEED FUNCTIONS ────────────────────────────────────────────────────────────

async function seedAbbreviations() {
  console.log("Seeding abbreviations...");
  for (const entry of ABBREVIATIONS) {
    await db
      .insert(abbreviationMapTable)
      .values(entry)
      .onConflictDoUpdate({
        target: abbreviationMapTable.abbreviation,
        set: { expansions: entry.expansions, category: entry.category },
      });
  }
  console.log(`✓ Seeded ${ABBREVIATIONS.length} abbreviations`);
}

export async function seedVendors() {
  console.log("Seeding vendor map...");
  for (const entry of VENDORS) {
    await db
      .insert(vendorMapTable)
      .values({ ...entry, isPrimary: false })
      .onConflictDoUpdate({
        target: vendorMapTable.code,
        set: { names: entry.names, notes: entry.notes, isPrimary: false },
      });
  }
  for (const entry of PRIMARY_VENDORS) {
    await db
      .insert(vendorMapTable)
      .values(entry)
      .onConflictDoUpdate({
        target: vendorMapTable.code,
        set: { names: entry.names, notes: entry.notes, isPrimary: true },
      });
  }
  console.log(`✓ Seeded ${PRIMARY_VENDORS.length} primary vendors + ${VENDORS.length} extended vendors`);
}

